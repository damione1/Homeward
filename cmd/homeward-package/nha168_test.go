func packageFixture(t *testing.T) (string, string, string) {
	t.Helper()
	root := t.TempDir()
	paths := []string{filepath.Join(root, "server"), filepath.Join(root, "credentials"), filepath.Join(root, "postgres")}
	for _, path := range paths {
		if err := os.Mkdir(path, 0700); err != nil {
			t.Fatal(err)
		}
	}
	return paths[0], paths[1], paths[2]
}

func TestNHA168PreparePreservesDeploymentAndLeavesMasterKeyToServer(t *testing.T) {
	server, credentials, postgres := packageFixture(t)
	if err := prepare(server, credentials, postgres, "homeward.example"); err != nil {
		t.Fatal(err)
	}
	names := []string{filepath.Join(credentials, "password"), filepath.Join(server, "configuration.yaml"), filepath.Join(server, "data/server.key"), filepath.Join(server, "data/server.crt"), filepath.Join(server, "package.json")}
	before := make(map[string][]byte)
	for _, name := range names {
		info, err := os.Lstat(name)
		if err != nil || info.Mode().Perm() != 0600 {
			t.Fatal("deployment file is not private")
		}
		before[name], err = os.ReadFile(name)
		if err != nil {
			t.Fatal(err)
		}
	}
	if _, err := os.Stat(filepath.Join(server, "data/.env")); !os.IsNotExist(err) {
		t.Fatal("package generated server encryption key")
	}
	if _, err := config.ParseWithEnv(before[filepath.Join(server, "configuration.yaml")], func(name string) (string, bool) {
		return string(before[filepath.Join(credentials, "password")]), name == "HOMEWARD_POSTGRES_PASSWORD"
	}); err != nil {
		t.Fatal("package YAML does not match current server grammar", err)
	}
	if err := os.WriteFile(filepath.Join(postgres, "PG_VERSION"), []byte("17"), 0600); err != nil {
		t.Fatal(err)
	}
	if err := prepare(server, credentials, postgres, "homeward.example"); err != nil {
		t.Fatal("recreation refused intact deployment", err)
	}
	for name, want := range before {
		got, err := os.ReadFile(name)
		if err != nil || !bytes.Equal(got, want) {
			t.Fatal("recreation changed established deployment")
		}
	}
	pair, err := tls.X509KeyPair(before[filepath.Join(server, "data/server.crt")], before[filepath.Join(server, "data/server.key")])
	if err != nil {
		t.Fatal("invalid TLS pair", err)
	}
	certificate, err := x509.ParseCertificate(pair.Certificate[0])
	if err != nil || certificate.VerifyHostname("homeward.example") != nil {
		t.Fatal("certificate has no configured identity")
	}
	block, _ := pem.Decode(before[filepath.Join(server, "data/server.crt")])
	if block == nil || block.Type != "CERTIFICATE" {
		t.Fatal("missing trust certificate")
	}
}

func TestNHA168PrepareRefusesCredentialLossPartialFilesAndExistingDatabase(t *testing.T) {
	for _, scenario := range []string{"database", "partial", "symlink", "credential-loss", "hostname-change"} {
		t.Run(scenario, func(t *testing.T) {
			server, credentials, postgres := packageFixture(t)
			hostname := "localhost"
			switch scenario {
			case "database":
				if err := os.WriteFile(filepath.Join(postgres, "PG_VERSION"), []byte("17"), 0600); err != nil {
					t.Fatal(err)
				}
			case "partial":
				if err := os.WriteFile(filepath.Join(credentials, "password"), []byte("retained"), 0600); err != nil {
					t.Fatal(err)
				}
			case "symlink":
				if err := os.Symlink(filepath.Join(t.TempDir(), "untouched"), filepath.Join(server, "configuration.yaml")); err != nil {
					t.Fatal(err)
				}
			default:
				if err := prepare(server, credentials, postgres, hostname); err != nil {
					t.Fatal(err)
				}
				if scenario == "credential-loss" {
					if err := os.Remove(filepath.Join(credentials, "password")); err != nil {
						t.Fatal(err)
					}
				} else {
					hostname = "different.example"
				}
			}
			if err := prepare(server, credentials, postgres, hostname); err == nil {
				t.Fatal("unsafe initialization was accepted")
			}
			if scenario == "database" || scenario == "credential-loss" {
				if _, err := os.Stat(filepath.Join(credentials, "password")); !os.IsNotExist(err) {
					t.Fatal("database password silently regenerated")
				}
			}
			if _, err := os.Stat(filepath.Join(server, "data/.env")); !os.IsNotExist(err) {
				t.Fatal("server key was generated by package")
			}
		})
	}
}

