#!/usr/bin/env python3
"""Generate exact Host 1.0/1.1 digests; verify the 1.0 parent descriptor."""
import hashlib
import io
import pathlib
import subprocess
import sys
import tarfile
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
PARENT = "a7ea662f89d6523095bbc54a371fca9192d497b8"
HISTORICAL_DIGEST = "c363e86d3419af3de9fad141bb43465f6669b9edcbb6ddfab4561c7561d5ec88"
legacy = ROOT / "testworker/fixtures/host-v1.0.pb"
legacy_digest = hashlib.sha256(legacy.read_bytes()).hexdigest()
if legacy_digest != HISTORICAL_DIGEST:
    raise SystemExit("Host 1.0 historical descriptor fixture changed")
# The versioned descriptor is sufficient for depth-1/source archives. When
# the parent object is available, also regenerate it from those exact sources.
try:
    available = subprocess.run(
        ["git", "cat-file", "-e", PARENT + "^{commit}"], cwd=ROOT,
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        check=False,
    ).returncode == 0
except FileNotFoundError:
    available = False
if available:
    with tempfile.TemporaryDirectory(prefix="homeward-host-legacy-") as temp:
        archive = subprocess.run(
            ["git", "archive", PARENT, "buf.yaml", "proto"], cwd=ROOT,
            check=True, capture_output=True,
        ).stdout
        with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
            tar.extractall(temp, filter="data")
        historical = pathlib.Path(temp) / "historical.pb"
        subprocess.run(
            ["buf", "build", "--path", "proto/home/integrations/v1/host.proto",
             "--exclude-source-info", "-o", str(historical)], cwd=temp, check=True,
        )
        if legacy.read_bytes() != historical.read_bytes():
            raise SystemExit("Host 1.0 fixture differs from committed parent descriptor")
with tempfile.TemporaryDirectory(prefix="homeward-host-schema-") as temp:
    descriptor = pathlib.Path(temp) / "host.pb"
    subprocess.run(
        ["buf", "build", "--path", "proto/home/integrations/v1/host.proto",
         "--exclude-source-info", "-o", str(descriptor)],
        cwd=ROOT, check=True,
    )
    digest = hashlib.sha256(descriptor.read_bytes()).hexdigest()

files = {
    ROOT / "internal/worker/schema_digest.go": (
        "// Code generated by scripts/host-schema.py; DO NOT EDIT.\n"
        "package worker\n\nconst schemaDigestV10Hex = \"" + legacy_digest + "\"\n"
        "const schemaDigestV11Hex = \"" + digest + "\"\n"
    ),
    ROOT / "testworker/schema_digest.py": (
        "# Generated by scripts/host-schema.py; DO NOT EDIT.\n"
        "LEGACY_SCHEMA_DIGEST_HEX = \"" + legacy_digest + "\"\n"
        "SCHEMA_DIGEST_HEX = \"" + digest + "\"\n"
    ),
}
check = len(sys.argv) == 2 and sys.argv[1] == "--check"
if len(sys.argv) > 2 or (len(sys.argv) == 2 and not check):
    raise SystemExit("usage: host-schema.py [--check]")
for path, contents in files.items():
    if check:
        if not path.exists() or path.read_text() != contents:
            raise SystemExit(f"stale Host descriptor digest: {path}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents)
print("Host 1.0/1.1 descriptor SHA-256:", legacy_digest, digest)
