#!/usr/bin/env python3
"""Emit the sole current Host/driver descriptor digest from the locked sources."""
import hashlib
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
HOST_MAJOR, HOST_MINOR = 1, 6
check = len(sys.argv) == 2 and sys.argv[1] == "--check"
if len(sys.argv) > 2 or (len(sys.argv) == 2 and not check):
    raise SystemExit("usage: host-schema.py [--check]")
# Resolve the current transitive descriptor from buf.lock and the current source
# tree. No Git revision, archived profile or prior descriptor is consulted.
with tempfile.TemporaryDirectory(prefix="homeward-host-current-") as temp:
    descriptor = pathlib.Path(temp) / "host.pb"
    subprocess.run(
        ["buf", "build", "--path", "proto/home/integrations/v1/host.proto",
         "--exclude-source-info", "-o", str(descriptor)], cwd=ROOT, check=True,
    )
    digest = hashlib.sha256(descriptor.read_bytes()).hexdigest()
files = {
    ROOT / "internal/worker/schema_digest.go": (
        "// Code generated by scripts/host-schema.py; DO NOT EDIT.\n"
        "package worker\n\nconst schemaDigestHex = \"" + digest + "\"\n"
    ),
    ROOT / "testworker/schema_digest.py": (
        "# Generated by scripts/host-schema.py; DO NOT EDIT.\n"
        f"HOST_MAJOR = {HOST_MAJOR}\nHOST_MINOR = {HOST_MINOR}\n"
        f"SCHEMA_DIGEST_HEX = \"{digest}\"\n"
    ),
}
for path, contents in files.items():
    if check:
        if not path.exists() or path.read_text() != contents:
            raise SystemExit(f"stale current Host descriptor digest: {path}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents)
print(f"Host/driver {HOST_MAJOR}.{HOST_MINOR} current descriptor SHA-256: {digest}")
