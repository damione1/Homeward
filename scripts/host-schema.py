#!/usr/bin/env python3
"""Generate Host 1.3 digest; preserve the exact Host 1.0–1.2 profiles."""
import hashlib
import io
import pathlib
import subprocess
import sys
import tarfile
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
PROFILES = {
    "1.0": ("a7ea662f89d6523095bbc54a371fca9192d497b8",
            "c363e86d3419af3de9fad141bb43465f6669b9edcbb6ddfab4561c7561d5ec88"),
    "1.1": ("6f4b74e3e1eb19843d3b3011819b554bd1b8af03",
            "1d72cec9576e703a3b14c0d3c93e9eca144fc1d52f7fdd47521d6edbe58f3286"),
    "1.2": ("8b7e6b3905a351f06ec0230c9e793067bf958ea2",
            "d0387fda259b28a927908aba972efeb64088ea439a6feda8da210a3d9874fe28"),
}
for version, (parent, expected) in PROFILES.items():
    legacy = ROOT / ("testworker/fixtures/host-v" + version + ".pb")
    if hashlib.sha256(legacy.read_bytes()).hexdigest() != expected:
        raise SystemExit("Host " + version + " historical descriptor fixture changed")
    # Source archives/depth-1 checkouts can use the pinned descriptor directly.
    # When available, also reproduce it from the exact committed parent sources.
    try:
        available = subprocess.run(
            ["git", "cat-file", "-e", parent + "^{commit}"], cwd=ROOT,
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            check=False,
        ).returncode == 0
    except FileNotFoundError:
        available = False
    if available:
        with tempfile.TemporaryDirectory(prefix="homeward-host-legacy-") as temp:
            archive = subprocess.run(
                ["git", "archive", parent, "buf.yaml", "proto"], cwd=ROOT,
                check=True, capture_output=True,
            ).stdout
            with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
                tar.extractall(temp, filter="data")
            historical = pathlib.Path(temp) / "historical.pb"
            subprocess.run(
                ["buf", "build", "--path", "proto/home/integrations/v1/host.proto",
                 "--exclude-source-info", "-o", str(historical)], cwd=temp, check=True,
            )
            if legacy.read_bytes() != historical.read_bytes():
                raise SystemExit("Host " + version + " fixture differs from committed parent descriptor")
with tempfile.TemporaryDirectory(prefix="homeward-host-schema-") as temp:
    descriptor = pathlib.Path(temp) / "host.pb"
    subprocess.run(
        ["buf", "build", "--path", "proto/home/integrations/v1/host.proto",
         "--exclude-source-info", "-o", str(descriptor)],
        cwd=ROOT, check=True,
    )
    digest = hashlib.sha256(descriptor.read_bytes()).hexdigest()

files = {
    ROOT / "internal/worker/schema_digest.go": (
        "// Code generated by scripts/host-schema.py; DO NOT EDIT.\n"
        "package worker\n\nconst schemaDigestV10Hex = \"" + PROFILES["1.0"][1] + "\"\n"
        "const schemaDigestV11Hex = \"" + PROFILES["1.1"][1] + "\"\n"
        "const schemaDigestV12Hex = \"" + PROFILES["1.2"][1] + "\"\n"
        "const schemaDigestV13Hex = \"" + digest + "\"\n"
    ),
    ROOT / "testworker/schema_digest.py": (
        "# Generated by scripts/host-schema.py; DO NOT EDIT.\n"
        "LEGACY_SCHEMA_DIGEST_HEX = \"" + PROFILES["1.0"][1] + "\"\n"
        "SCHEMA_DIGEST_HEX = \"" + PROFILES["1.1"][1] + "\"\n"
        "SCHEMA_DIGEST_V12_HEX = \"" + PROFILES["1.2"][1] + "\"\n"
        "SCHEMA_DIGEST_V13_HEX = \"" + digest + "\"\n"
    ),
}
check = len(sys.argv) == 2 and sys.argv[1] == "--check"
if len(sys.argv) > 2 or (len(sys.argv) == 2 and not check):
    raise SystemExit("usage: host-schema.py [--check]")
for path, contents in files.items():
    if check:
        if not path.exists() or path.read_text() != contents:
            raise SystemExit(f"stale Host descriptor digest: {path}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents)
print("Host 1.0/1.1/1.2/1.3 descriptor SHA-256:",
      PROFILES["1.0"][1], PROFILES["1.1"][1], PROFILES["1.2"][1], digest)
